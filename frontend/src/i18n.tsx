const messages: Record<Language, Record<MessageKey, string>> = { en: english, de: german }

export function translate(language: Language, key: MessageKey, values?: Values) {
  let message = messages[language][key]
  for (const [name, value] of Object.entries(values ?? {})) message = message.replaceAll(`{${name}}`, String(value))
  return message
}

type I18nValue = {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: MessageKey, values?: Values) => string
}

const I18nContext = createContext<I18nValue | null>(null)

function initialLanguage(): Language {
  try {
    return localStorage.getItem('logtracer.language') === 'de' ? 'de' : 'en'
  } catch {
    return 'en'
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage)
  useEffect(() => {
    document.documentElement.lang = language
    try { localStorage.setItem('logtracer.language', language) } catch { /* Storage may be disabled. */ }
  }, [language])
  const value = useMemo<I18nValue>(() => ({ language, setLanguage, t: (key, values) => translate(language, key, values) }), [language])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
